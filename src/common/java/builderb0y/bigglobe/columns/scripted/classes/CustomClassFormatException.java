package builderb0y.bigglobe.columns.scripted.classes;

public class CustomClassFormatException extends Exception {

	public CustomClassFormatException() {
	}

	public CustomClassFormatException(String message) {
		super(message);
	}

	public CustomClassFormatException(Throwable cause) {
		super(cause);
	}

	public CustomClassFormatException(String message, Throwable cause) {
		super(message, cause);
	}
}
package builderb0y.bigglobe.classes.compile;

public class ConstantFormatException extends Exception {

	public ConstantFormatException() {}

	public ConstantFormatException(String message) {
		super(message);
	}

	public ConstantFormatException(Throwable cause) {
		super(cause);
	}

	public ConstantFormatException(String message, Throwable cause) {
		super(message, cause);
	}
}